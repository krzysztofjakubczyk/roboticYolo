public class Face {

    private int resId;

    private String name;

    private String text;

    private String theme;

    private int index;

    private int pngResId;

    public int getResId() {
        return resId;
    }

    public void setResId(int resId) {
        this.resId = resId;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getText() {
        return text;
    }

    public void setText(String text) {
        this.text = text;
    }

    public String getTheme() {
        return theme;
    }

    public void setTheme(String theme) {
        this.theme = theme;
    }

    public int getIndex() {
        return index;
    }

    public void setIndex(int index) {
        this.index = index;
    }

    public int getPngResId() {
        return pngResId;
    }

    public void setPngResId(int pngResId) {
        this.pngResId = pngResId;
    }
}
